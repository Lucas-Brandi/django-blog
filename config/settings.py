def env_int(name, default):
    """Lê uma variável de ambiente inteira (usa o padrão se ausente/inválida)."""
    value = os.environ.get(name)
    if value is None or value.strip() == "":
        return default
    try:
        return int(value)
    except ValueError:
        return default


